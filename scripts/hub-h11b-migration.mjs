// Guest Hub H11b (24 Nov 2026 — after the full production lab): writes supabase/migrations/20261124200000_guest_hub_h11b.sql —
// the reception-from-the-room-phone card read only on its branch's number (internal.hub_branch_only_cards, the twin of
// retrieval.ts → BRANCH_ONLY), and the bank's corrections of tests/hub-bank/corrections.json whose migration is this one.
// Run ONCE before the migration is applied; never after (CLAUDE.md §12) — then it only checks.
//   node scripts/hub-h11b-migration.mjs [--force]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
export const OUT_PATH = 'supabase/migrations/20261124200000_guest_hub_h11b.sql';
const OUT = new URL(`../${OUT_PATH}`, import.meta.url);
const sqlJson = (o) => JSON.stringify(o).replace(/":/g, '": ').replace(/,"/g, ', "').replace(/'/g, "''");
export const BRANCH_ONLY_SQL = ['k-cafe-menu', 'k-cafe-phone', 'k-cafe-breakfast-menu', 'k-reception-room-phone'];

export function migration() {
  const all = JSON.parse(read('tests/hub-bank/corrections.json')).items;
  const corr = Object.entries(all).filter(([, c]) => c.migration === OUT_PATH.split('/').pop())
    .map(([id, c]) => `update public.hub_test_items\n   set expect = '${sqlJson(c.expect)}'::jsonb\n where key = '${id}' and expect = '${sqlJson(c.old)}'::jsonb;`).join('\n');
  return `-- Guest Hub H11b (24 Nov 2026 — DECISIONS.md 2026-11-24 «Guest Hub H11»): after the full production lab. Generated by
-- scripts/hub-h11b-migration.mjs — never edited once applied (CLAUDE.md §12). Every UPDATE carries a WHERE.
--   The reception-from-the-room-phone card (Airport Road, «اضغط 0») was read on the Shafa Road number and answered there:
--   it is a branch-only card, read on another number only when the guest names Airport Road.
--   The bank: q067 (package questions are answered from the offer since 18 Nov 2026), c131 / c132 / c136 (the extension
--   asks the date first, or hands off at once with the length given), c146 (the summary is not sent again unchanged).

create or replace function internal.hub_branch_only_cards() returns text[]
language sql immutable set search_path = '' as $$ select array[${BRANCH_ONLY_SQL.map((k) => `'${k}'`).join(', ')}] $$;

${corr}
`;
}

const isMain = process.argv[1] && new URL(import.meta.url).pathname.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop());
if (isMain) {
  const out = migration();
  if (existsSync(OUT) && !process.argv.includes('--force')) {
    if (readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') !== out) {
      console.error(`${OUT_PATH} differs from its generator — never regenerate an applied migration (CLAUDE.md §12)`);
      process.exit(1);
    }
    console.log(`✓ ${OUT_PATH} = its generator`);
  } else {
    writeFileSync(OUT, out, 'utf8');
    console.log(`✓ wrote ${OUT_PATH}`);
  }
}
