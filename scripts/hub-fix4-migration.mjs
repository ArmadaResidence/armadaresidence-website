function edit(fn, name, from, to, times = 1) {
  const n = fn.split(from).length - 1;
  if (n !== times) throw new Error(`${name}: an edit matched ${n} times (expected ${times}) — ${from.slice(0, 80)}`);
  return fn.split(from).join(to);
}
