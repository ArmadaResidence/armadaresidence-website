// Guest Hub S2d (26 Nov 2026 — the lab of «السوشيال» after S2c, DECISIONS.md 2026-11-26 «Guest Hub S2 — comments»): writes
// supabase/migrations/20261126400000_guest_hub_s2d.sql. Run ONCE before it is applied; never after.
//   node scripts/hub-s2d-migration.mjs [--force]
// The knowledge read of a unit with no branch («السوشيال»): its own key is one of its units, so a card tagged «السوشيال»
// ranks first — before, `branch_slug = NULL` matched no unit, every card ranked «another branch's» and the five went by
// their sort, so Ahmed's bathroom amenities card (tagged both branches and «السوشيال», sort 913) was never read and
// «عندكوا شامبو؟» asked the branch (s2-01). A branch or dining unit is unchanged (it is already among its branch's units).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fnFrom } from './hub-team-migration.mjs';

export const OUT_PATH = 'supabase/migrations/20261126400000_guest_hub_s2d.sql';
const OUT = new URL(`../${OUT_PATH}`, import.meta.url);
const SRC = 'supabase/migrations/20261117100000_guest_hub_fix3.sql';
export const FROM = '  v_keys := array(select x.key from public.hub_units x where x.branch_slug = u.branch_slug);';
export const TO = `  -- S2d: a unit with no branch («السوشيال») is one of its own units (a card tagged with it ranks first)
  v_keys := array(select x.key from public.hub_units x where x.branch_slug = u.branch_slug or x.id = u.id);`;
function edit(fn, name) {
  const n = fn.split(FROM).length - 1;
  if (n !== 1) throw new Error(`${name}: the edit matched ${n} times`);
  return fn.replace(FROM, () => TO);
}

export function migration() {
  return `-- Guest Hub S2d (26 Nov 2026 — DECISIONS.md 2026-11-26 «Guest Hub S2 — comments»): the knowledge read of a unit with no
-- branch («السوشيال») counts the unit itself among its units. Generated by scripts/hub-s2d-migration.mjs — never edited once
-- applied (CLAUDE.md §12). No unit mode, licence or switch changes; no UPDATE or DELETE.

${edit(fnFrom(SRC, 'public.hub_knowledge_for'), 'hub_knowledge_for')}

${edit(fnFrom(SRC, 'public.hub_knowledge_for_eval'), 'hub_knowledge_for_eval')}
`;
}

if (process.argv[1]?.endsWith('hub-s2d-migration.mjs')) {
  const sql = migration();
  if (existsSync(OUT) && !process.argv.includes('--force')) {
    if (readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') !== sql) { console.error(`✗ ${OUT_PATH} differs from its generator`); process.exit(1); }
    console.log(`✓ ${OUT_PATH} = its generator`);
  } else {
    writeFileSync(OUT, sql, 'utf8');
    console.log(`✓ wrote ${OUT_PATH}`);
  }
}
