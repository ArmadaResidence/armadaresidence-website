//   - internal.hub_comments_retention writes ONE audit row of counts per run (as public.hub_retention does — never a word);
//   - the policies page gains the section «المراسلة عبر واتساب وانستجرام وماسنجر والتعليقات» after «عضوية إياب والتسويق»
//     (index 9): the «المحتوى والظهور» fields of «الجهة المشغّلة» move from index 10 to 11 (paths and anchor).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

export const OUT_PATH = 'supabase/migrations/20261126950000_guest_hub_s3c.sql';
const OUT = new URL(`../${OUT_PATH}`, import.meta.url);

export function migration() {
  return `-- Guest Hub S3c (26 Nov 2026 — Ahmed's approval of the privacy paragraph; DECISIONS.md 2026-11-26 «Guest Hub S3c»): the purge
-- the paragraph promises (message texts 12 months, photos and voice messages 90 days, comments 12 months) runs every day; the
-- comments' purge is audited with counts; the policies page's «الجهة المشغّلة» fields follow the new section. Generated by
-- scripts/hub-s3c-migration.mjs — never edited once applied (CLAUDE.md §12). No mode, licence or switch changes. Every UPDATE
-- has a WHERE.

-- ── 1. the purge every day (it ran on the 1st of the month) ──
select cron.schedule('hub-retention', '37 2 * * *', 'select public.hub_retention()');
select cron.schedule('hub-comments-retention', '23 3 * * *', 'select internal.hub_comments_retention()');

-- ── 2. the comments' purge audited with counts only ──
create or replace function internal.hub_comments_retention() returns integer
language plpgsql security definer set search_path = '' as $$
declare v_n integer;
begin
  update public.hub_comments set body = null, author_name = null, public_body = null, private_body = null
   where received_at < now() - interval '12 months' and (body is not null or author_name is not null or public_body is not null or private_body is not null);
  get diagnostics v_n = row_count;
  -- S3c: one audit row of counts per run (never a word or a name)
  insert into public.audit_log (actor_id, actor_label, entity, entity_id, branch, action, old, new, batch_id)
  values (null, 'retention', 'hub_comments_retention', to_char(now() at time zone 'Asia/Riyadh', 'YYYY-MM-DD'), null, 'update', null,
          jsonb_build_object('comments', v_n, 'months', 12), gen_random_uuid());
  return v_n;
end;
$$;
revoke execute on function internal.hub_comments_retention() from public, anon, authenticated;

-- ── 3. «الجهة المشغّلة» moves from section 10 to 11 (the new section «messaging» is index 9) ──
update public.content_fields
   set path_ar[3] = '11', path_en[3] = '11',
       anchor = '[{"path": ["page", "sections", "11", "id"], "value": "operator"}]'::jsonb
 where key in ('policy.operator.heading', 'policy.operator.body') and file = 'policies.json' and path_ar[3] = '10' and path_en[3] = '10';
`;
}

if (process.argv[1]?.endsWith('hub-s3c-migration.mjs')) {
  const sql = migration();
  if (existsSync(OUT) && !process.argv.includes('--force')) {
    const cur = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
    if (cur !== sql) { console.error(`✗ ${OUT_PATH} differs from its generator`); process.exit(1); }
    console.log(`✓ ${OUT_PATH} = its generator`);
  } else {
    writeFileSync(OUT, sql, 'utf8');
    console.log(`✓ wrote ${OUT_PATH}`);
  }
}
