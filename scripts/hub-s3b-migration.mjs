import { readFileSync, writeFileSync, existsSync } from 'node:fs';

export const OUT_PATH = 'supabase/migrations/20261126900000_guest_hub_s3b.sql';
const OUT = new URL(`../${OUT_PATH}`, import.meta.url);
const read = (f) => readFileSync(new URL(`../${f}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');

export function item() {
  const x = read('tests/hub-bank/conversations-social.jsonl').trim().split('\n').map((l) => JSON.parse(l)).find((r) => r.id === 's3-02');
  if (!x) throw new Error('s3-02 is missing from the bank');
  return x;
}

export function migration() {
  const x = item();
  return `-- Guest Hub S3b (26 Nov 2026 — DECISIONS.md 2026-11-26 «Guest Hub S3»): the lab item s3-02 corrected — 2–4 rooms on «السوشيال»
-- collect the details first (Ahmed, 15 Nov 2026), then go to the social team, never «فريق الاستقبال». Generated by
-- scripts/hub-s3b-migration.mjs — never edited once applied (CLAUDE.md §12). No mode, licence or switch changes. Every UPDATE has a WHERE.

update public.hub_test_items
   set messages = $s3b$${JSON.stringify(x.messages)}$s3b$::jsonb, expect = $s3b$${JSON.stringify(x.expect)}$s3b$::jsonb, note = $s3b$${x.note}$s3b$
 where key = 's3-02';
`;
}

if (process.argv[1]?.endsWith('hub-s3b-migration.mjs')) {
  const sql = migration();
  if (existsSync(OUT) && !process.argv.includes('--force')) {
    const cur = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
    if (cur !== sql) { console.error(`✗ ${OUT_PATH} differs from its generator`); process.exit(1); }
    console.log(`✓ ${OUT_PATH} = its generator`);
  } else {
    writeFileSync(OUT, sql, 'utf8');
    console.log(`✓ wrote ${OUT_PATH}`);
  }
}
