/** the H11 bank's guest conversations, as the lab seeds them */
export function h11BankItems() {
  return read('tests/hub-bank/conversations-h11.jsonl').split('\n').filter((l) => l.trim()).map((l) => JSON.parse(l))
    .filter((x) => !x._header && (x.kind ?? 'guest') === 'guest')
    .map((x) => ({ key: x.id, unit: x.unit, language: x.language, messages: x.messages, expect: x.expect, note: x.note ?? null, tags: x.tags, context: x.context ?? {} }));
}
/** the corrections of earlier bank items this migration applies */
export function h11Corrections() {
  const all = JSON.parse(read('tests/hub-bank/corrections.json')).items;
  const out = [];
  for (const [id, c] of Object.entries(all)) {
    const steps = [c, ...(c.then ?? [])];
    for (let i = 0; i < steps.length; i++) {
      if (steps[i].migration !== OUT_PATH.split('/').pop()) continue;
      out.push({ id, old: i === 0 ? c.old : steps[i - 1].expect, expect: steps[i].expect });
    }
  }
  return out;
}
