// Guest Hub H6 (14 Nov 2026): writes supabase/migrations/20261114400000_guest_hub_lab.sql from
// scripts/hub-lab-migration.src.sql, the test bank (tests/hub-bank/seed.jsonl, 102 questions) and the H5 function
// public.hub_knowledge_for (20261114200000_guest_hub_assistant.sql — its eval twin hub_knowledge_for_eval is the SAME text
// with one change: the cards a run is judging are read as their draft, as if published). Also writes
// supabase/functions/_shared/hub/bank-rules.generated.json: the bank header's global forbidden list and the fees the bank
// names that live in content/policies.json (late check-out, the key card) — the Edge Functions cannot read tests/ or
// content/. Run ONCE before the migration is applied; an applied migration is never edited (CLAUDE.md §12): after that
// the script refuses to overwrite it (pass --force only for a migration on no database yet). --rules-only rewrites the
// generated JSON alone.
//   node scripts/hub-lab-migration.mjs [--force | --rules-only]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const OUT = new URL('../supabase/migrations/20261114400000_guest_hub_lab.sql', import.meta.url);
const RULES = new URL('../supabase/functions/_shared/hub/bank-rules.generated.json', import.meta.url);

export function bankRows() {
  return read('tests/hub-bank/seed.jsonl').split('\n').filter((l) => l.trim()).map((l) => JSON.parse(l));
}
export function bankRules() {
  const rows = bankRows();
  const head = rows.find((r) => r._header);
  const pol = JSON.parse(read('content/policies.json'));
  return {
    _note: 'Generated by scripts/hub-lab-migration.mjs from tests/hub-bank/seed.jsonl (the header) and content/policies.json — do not edit; hub-eval-check fails when it is stale.',
    version: head.version,
    global_must_not_include: head.global_must_not_include,
    fees: {
      late_checkout_2pm: pol.late_checkout['until_14:00'],
      late_checkout_4pm: pol.late_checkout['until_16:00'],
      key_card: pol.key_card_loss_sar,
      breakfast_child_6_12: pol.children.breakfast['6_to_12'],
    },
  };
}
export function bankItems() {
  return bankRows().filter((r) => !r._header).map((r) => {
    for (const m of r.messages) if (/\{card:/.test(m)) throw new Error(`${r.id}: a card placeholder in a guest message`);
    return { id: r.id, unit: r.unit, language: r.language, messages: r.messages, ...(r.context ? { context: r.context } : {}), expect: r.expect, ...(r.note ? { note: r.note } : {}) };
  });
}
/** the eval twin of hub_knowledge_for: the same body, the cards of p_cards read as their draft */
export const CARD_SOURCE_H5 = `        from (select k.id, k.key, k.live, k.sort, array(select jsonb_array_elements_text(k.live -> 'unit_keys')) as unit_keys,
                     array(select jsonb_array_elements_text(k.live -> 'topic_keys')) as topic_keys
                from public.hub_knowledge_cards k
               where k.status = 'published' and k.live is not null and not k.is_test`;
export const CARD_SOURCE_EVAL = `        from (select k.id, k.key, k.live, k.sort, array(select jsonb_array_elements_text(k.live -> 'unit_keys')) as unit_keys,
                     array(select jsonb_array_elements_text(k.live -> 'topic_keys')) as topic_keys
                from (select x.id, x.key, x.sort, x.status,
                             case when x.id = any (coalesce(p_cards, '{}')) then false else x.is_test end as is_test,
                             case when x.id = any (coalesce(p_cards, '{}')) then internal.hub_card_snapshot(x) else x.live end as live
                        from public.hub_knowledge_cards x
                       where (x.id = any (coalesce(p_cards, '{}')) and x.status <> 'archived') or (x.status = 'published' and x.live is not null)) k
               where k.live is not null and not k.is_test`;
export function knowledgeForEval() {
  const mig = read('supabase/migrations/20261114200000_guest_hub_assistant.sql');
  const a = mig.indexOf('create function public.hub_knowledge_for(');
  const fn = mig.slice(a, mig.indexOf('\n$$;', a) + 4);
  if (!fn.includes(CARD_SOURCE_H5)) throw new Error('hub_knowledge_for: the card source moved');
  const head = 'create function public.hub_knowledge_for(p_unit text, p_topics text[], p_language text, p_branch text default null) returns jsonb';
  if (!fn.startsWith(head)) throw new Error('hub_knowledge_for: the signature moved');
  return [
    '-- the knowledge read of a test-lab run: public.hub_knowledge_for (H5) with the cards being judged (p_cards — drafts and',
    '-- edits) read as if published; generated from the H5 function by scripts/hub-lab-migration.mjs (hub-eval-check proves it)',
    fn.replace(head, 'create function public.hub_knowledge_for_eval(p_unit text, p_topics text[], p_language text, p_branch text default null, p_cards uuid[] default null) returns jsonb')
      .replace(CARD_SOURCE_H5, CARD_SOURCE_EVAL),
  ].join('\n');
}
export function migration() {
  const src = read('scripts/hub-lab-migration.src.sql');
  const items = JSON.stringify(bankItems());
  if (items.includes('$seed_bank$')) throw new Error('a dollar-quote tag inside the bank');
  if (/k-wifi-password-[a-z]+["']?\s*:/.test(items)) throw new Error('a Wi-Fi card text in the bank');
  // a function replacer: a replacement string would turn the function's $$ into $
  return src.replace('/*@BANK_JSON@*/', () => items).replace('/*@KNOWLEDGE_FOR_EVAL@*/', () => knowledgeForEval());
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, '/').replace(/^\//, '')}` || process.argv[1]?.endsWith('hub-lab-migration.mjs')) {
  writeFileSync(RULES, JSON.stringify(bankRules(), null, 1) + '\n', 'utf8');
  console.log('✓ wrote supabase/functions/_shared/hub/bank-rules.generated.json');
  if (!process.argv.includes('--rules-only')) {
    if (existsSync(OUT) && !process.argv.includes('--force')) {
      console.error('hub-lab-migration: the migration exists — an applied migration is never edited (pass --force only before it is applied)');
      process.exit(1);
    }
    writeFileSync(OUT, migration(), 'utf8');
    console.log('✓ wrote supabase/migrations/20261114400000_guest_hub_lab.sql');
  }
}
