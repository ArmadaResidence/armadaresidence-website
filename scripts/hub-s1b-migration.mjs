// supabase/migrations/20261125200000_guest_hub_social_lab.sql. Run ONCE before it is applied; never after — then it checks.
//   node scripts/hub-s1b-migration.mjs [--force]
// «السوشيال» is judged by its OWN lab and its OWN licences (Ahmed's «يرد تلقائيًا» gate reads «a full lab run of the
// social unit's questions»): the brand unit's special cases of S1 in internal.hub_test_lab_ready and hub_turn_claim are
// taken out (every unit the same rule again — stricter: its licences start «بموافقة الفريق»); the lab's context carries
// the channel's kind and provider and both branches' price switch for a unit with no branch; the social bank's engine
// conversations (s1-01 … s1-08) become lab items of the unit «social».
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fnFrom } from './hub-team-migration.mjs';

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
export const OUT_PATH = 'supabase/migrations/20261125200000_guest_hub_social_lab.sql';
const OUT = new URL(`../${OUT_PATH}`, import.meta.url);
function edit(fn, name, from, to) {
  const n = fn.split(from).length - 1;
  if (n !== 1) throw new Error(`${name}: an edit matched ${n} times — ${from.slice(0, 90)}`);
  return fn.replace(from, () => to);
}
const M = (f) => `supabase/migrations/${f}`;
export const SOURCES = {
  'public.hub_eval_context': M('20261114400000_guest_hub_lab.sql'),
  'internal.hub_test_lab_ready': M('20261125100000_guest_hub_social.sql'),
  'public.hub_turn_claim': M('20261125100000_guest_hub_social.sql'),
};

const HEAD = `-- Guest Hub S1b (25 Nov 2026, Ahmed — DECISIONS.md 2026-11-25 «Guest Hub S1b»): «السوشيال» judged by its own lab and its
-- own licences; the lab's context with the channel's kind; the social bank as lab items. Generated by
-- scripts/hub-s1b-migration.mjs — never edited once applied (CLAUDE.md §12).
-- No unit mode, licence or switch changes. No phone number in this file. Every UPDATE / DELETE carries a WHERE.
`;

/** the social bank's engine conversations (the deletion items are the router's, not engine turns) */
export function socialItems() {
  return read('tests/hub-bank/conversations-social.jsonl').split('\n').filter((l) => l.trim()).map((l) => JSON.parse(l))
    .filter((x) => !x._header && !x.kind)
    .map((x) => ({ key: x.id, unit: x.unit, language: x.language, messages: x.messages, expect: x.expect, note: x.note ?? null, tags: x.tags, context: x.context ?? {},
                   ...(x.offers ? { offers: x.offers } : {}) }));
}

export function migration() {
  const get = (n) => fnFrom(SOURCES[n], n);
  const out = [];

  let ec = get('public.hub_eval_context');
  ec = edit(ec, 'eval_context', `    'channel', (select jsonb_build_object('address', ch.address, 'sending_enabled', false) from public.hub_channels ch where ch.unit_id = u.id order by ch.created_at limit 1),`,
    `    -- S1b: the channel's kind and provider (a Meta channel asks the mobile number for a booking)
    'channel', (select jsonb_build_object('address', ch.address, 'sending_enabled', false, 'kind', ch.kind, 'provider', ch.provider) from public.hub_channels ch where ch.unit_id = u.id order by ch.created_at limit 1),`);
  ec = edit(ec, 'eval_context', `      'show_prices', coalesce((select (s.value ->> u.branch_slug)::boolean from public.settings s where s.key = 'show_prices'), false)),`,
    `      'show_prices', coalesce((select case when u.branch_slug is null then (s.value ->> 'airport-road')::boolean and (s.value ->> 'shafa-road')::boolean
                                           else (s.value ->> u.branch_slug)::boolean end from public.settings s where s.key = 'show_prices'), false)),`);
  out.push(ec);

  let lr = get('internal.hub_test_lab_ready');
  lr = edit(lr, 'lab_ready', `  select case when u.kind = 'brand' then coalesce((select bool_and(internal.hub_test_lab_ready(b)) and count(*) > 0
                                                    from public.hub_units b where b.kind = 'branch' and b.status = 'active'), false)
  else (internal.hub_unit_lab(u) ->> 'run_id') is not null`, `  -- S1b: every unit by its OWN latest full run («السوشيال» included — its own questions)
  select (internal.hub_unit_lab(u) ->> 'run_id') is not null`);
  lr = edit(lr, 'lab_ready', `     and coalesce((internal.hub_unit_lab(u) ->> 'items')::int, 0) > 0 end\n$$;`, `     and coalesce((internal.hub_unit_lab(u) ->> 'items')::int, 0) > 0\n$$;`);
  out.push(lr);

  let cl = get('public.hub_turn_claim');
  cl = edit(cl, 'turn_claim', `    -- S1: a brand unit has no licences of its own — each topic takes the most restrictive of the active branch units'
    'licences', case when u.kind = 'brand' then
                  (select coalesce(jsonb_object_agg(z.topic_key, z.mode), '{}') from (
                     select l.topic_key, case when bool_or(l.mode = 'blocked') then 'blocked' when bool_or(l.mode = 'shadow') then 'shadow' else 'auto' end as mode
                       from public.hub_licences l join public.hub_units b on b.id = l.unit_id where b.kind = 'branch' and b.status = 'active' group by l.topic_key) z)
                else (select coalesce(jsonb_object_agg(l.topic_key, l.mode), '{}') from public.hub_licences l where l.unit_id = u.id) end,`,
    `    -- S1b: every unit by its OWN licences («التراخيص»; «السوشيال» starts «بموافقة الفريق» — the system admin sets them)
    'licences', (select coalesce(jsonb_object_agg(l.topic_key, l.mode), '{}') from public.hub_licences l where l.unit_id = u.id),`);
  out.push(cl);

  const items = JSON.stringify(socialItems());
  if (items.includes('$s1b$')) throw new Error('the bank holds the dollar tag');
  out.push(`-- the social bank's engine conversations as lab items of «السوشيال» (the deletion items are the router's)
do $$
declare v_sort integer := coalesce((select max(sort) from public.hub_test_items), 0) + 1;
begin
  insert into public.hub_test_items (key, unit_key, language, messages, context, expect, note, tags, added_from, sort)
  select e ->> 'key', e ->> 'unit', e ->> 'language', e -> 'messages', coalesce(e -> 'context', '{}'::jsonb) || case when e ? 'offers' then jsonb_build_object('offers', e -> 'offers') else '{}'::jsonb end,
         e -> 'expect', e ->> 'note', array(select jsonb_array_elements_text(e -> 'tags')), 'seed', v_sort + (o - 1)::integer
    from jsonb_array_elements($s1b$${items}$s1b$::jsonb) with ordinality as x(e, o)
  on conflict (key) do nothing;
end $$;`);

  return `${HEAD}\n${out.join('\n\n')}\n`;
}

if (process.argv[1]?.endsWith('hub-s1b-migration.mjs')) {
  const sql = migration();
  if (existsSync(OUT) && !process.argv.includes('--force')) {
    const cur = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
    if (cur !== sql) { console.error(`✗ ${OUT_PATH} differs from its generator`); process.exit(1); }
    console.log(`✓ ${OUT_PATH} = its generator`);
  } else {
    writeFileSync(OUT, sql, 'utf8');
    console.log(`✓ wrote ${OUT_PATH}`);
  }
}
