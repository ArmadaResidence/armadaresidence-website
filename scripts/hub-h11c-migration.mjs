// Guest Hub H11c (Ahmed, 24 Nov 2026 — reception from the room phone is 0 at BOTH branches; Shafa Road rooms have phones):
// writes supabase/migrations/20261124300000_guest_hub_h11c.sql — the reception card k-reception-room-phone tagged both
// branches (its live copy too), no longer a branch-only card (internal.hub_branch_only_cards = retrieval.ts → BRANCH_ONLY),
// the two cards Ahmed taught by WhatsApp kept archived, the correction of h11-16 and the new cases of
// tests/hub-bank/conversations-h11c.jsonl as lab items. Run ONCE before the migration is applied; never after (CLAUDE.md §12).
//   node scripts/hub-h11c-migration.mjs [--force]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
export const OUT_PATH = 'supabase/migrations/20261124300000_guest_hub_h11c.sql';
const OUT = new URL(`../${OUT_PATH}`, import.meta.url);
const sqlJson = (o) => JSON.stringify(o).replace(/":/g, '": ').replace(/,"/g, ', "').replace(/'/g, "''");
export const BRANCH_ONLY_SQL = ['k-cafe-menu', 'k-cafe-phone', 'k-cafe-breakfast-menu'];

export function h11cBankItems() {
  return read('tests/hub-bank/conversations-h11c.jsonl').split('\n').filter((l) => l.trim()).map((l) => JSON.parse(l))
    .filter((x) => !x._header && (x.kind ?? 'guest') === 'guest')
    .map((x) => ({ key: x.id, unit: x.unit, language: x.language, messages: x.messages, expect: x.expect, note: x.note ?? null, tags: x.tags, context: x.context ?? {} }));
}
export function migration() {
  const all = JSON.parse(read('tests/hub-bank/corrections.json')).items;
  const corr = Object.entries(all).filter(([, c]) => c.migration === OUT_PATH.split('/').pop())
    .map(([id, c]) => `update public.hub_test_items\n   set expect = '${sqlJson(c.expect)}'::jsonb\n where key = '${id}' and expect = '${sqlJson(c.old)}'::jsonb;`).join('\n');
  return `-- Guest Hub H11c (Ahmed, 24 Nov 2026 — DECISIONS.md 2026-11-24 «Guest Hub H11c»): reception from the room phone is 0 at
-- BOTH branches (Shafa Road rooms have phones). Generated by scripts/hub-h11c-migration.mjs — never edited once applied
-- (CLAUDE.md §12). Every UPDATE carries a WHERE.

-- the one reception-extension card, both branches (its wording unchanged: Ahmed's)
update public.hub_knowledge_cards
   set unit_keys = '{airport-road,shafa-road}', source = 'أحمد — 24 نوفمبر 2026 (الفرعان)', source_date = '2026-11-24', verified_at = now()
 where key = 'k-reception-room-phone' and status = 'published';
update public.hub_knowledge_cards k set live = internal.hub_card_snapshot(k), published_at = now()
 where k.key = 'k-reception-room-phone' and k.status = 'published';

-- no longer a branch-only card (= retrieval.ts → BRANCH_ONLY)
create or replace function internal.hub_branch_only_cards() returns text[]
language sql immutable set search_path = '' as $$ select array[${BRANCH_ONLY_SQL.map((k) => `'${k}'`).join(', ')}] $$;

-- the two copies Ahmed taught by WhatsApp (15 Nov 2026) stay archived: exactly one active reception-extension card
update public.hub_knowledge_cards
   set status = 'archived', archived_at = now()
 where key in ('k-811b0a03bd', 'k-c9ba44c369') and status = 'published' and learn_kind = 'teach';

-- the bank: h11-16 now expects «اضغط 0» on the Shafa Road number; a room-service / housekeeping extension → the team
${corr}
do $$
declare v_sort integer := coalesce((select max(sort) + 1 from public.hub_test_items), 0);
begin
  insert into public.hub_test_items (key, unit_key, language, messages, context, expect, note, tags, added_from, sort)
  select e ->> 'key', e ->> 'unit', e ->> 'language', e -> 'messages', coalesce(e -> 'context', '{}'::jsonb), e -> 'expect', e ->> 'note',
         array(select jsonb_array_elements_text(e -> 'tags')), 'seed', v_sort + (o - 1)::integer
    from jsonb_array_elements($h11c_bank$${JSON.stringify(h11cBankItems())}$h11c_bank$::jsonb) with ordinality as x(e, o)
  on conflict (key) do nothing;
end $$;
`;
}

const isMain = process.argv[1] && new URL(import.meta.url).pathname.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop());
if (isMain) {
  const out = migration();
  if (existsSync(OUT) && !process.argv.includes('--force')) {
    if (readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') !== out) {
      console.error(`${OUT_PATH} differs from its generator — never regenerate an applied migration (CLAUDE.md §12)`);
      process.exit(1);
    }
    console.log(`✓ ${OUT_PATH} = its generator`);
  } else {
    writeFileSync(OUT, out, 'utf8');
    console.log(`✓ wrote ${OUT_PATH}`);
  }
}
