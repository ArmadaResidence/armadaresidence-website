// Guest Hub — reply speed (15 Nov 2026, Ahmed 21:10: «replies feel slow on WhatsApp»): writes
// supabase/migrations/20261115700000_guest_hub_speed.sql from the LATEST definitions of the functions it edits (each edit
// must match exactly once). Run ONCE before the migration is applied; never after (CLAUDE.md §12) — then it only checks.
//   1. The wait for more messages of the same burst (hub_burst_ms) is at most 3 seconds: the setting's range 0–3000, the
//      stored value 4000 → 2000, and hub_turn_queue caps whatever it reads at 3000.
//   node scripts/hub-speed-migration.mjs [--force]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fnFrom } from './hub-team-migration.mjs';

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
export const OUT_PATH = 'supabase/migrations/20261115700000_guest_hub_speed.sql';
const OUT = new URL(`../${OUT_PATH}`, import.meta.url);
function edit(fn, name, from, to) {
  const n = fn.split(from).length - 1;
  if (n !== 1) throw new Error(`${name}: an edit matched ${n} times — ${from.slice(0, 80)}`);
  return fn.replace(from, () => to);
}
export const SOURCES = {
  'internal.hub_setting_int_range': 'supabase/migrations/20261115400000_guest_hub_media.sql',
  'public.hub_turn_queue': 'supabase/migrations/20261115200000_guest_hub_team.sql',
};

const HEAD = `-- Guest Hub — reply speed (15 Nov 2026, Ahmed 21:10: «everything works, but replies feel slow on WhatsApp»). Generated by
-- scripts/hub-speed-migration.mjs from the latest definitions of the functions it edits — never edited once applied
-- (CLAUDE.md §12). Measured from the stored turns since 14 Nov 20:52 Riyadh: of a text reply's median 14.3 s, 4.2 s
-- was the wait for more messages of the same burst (hub_burst_ms 4000).
--   1. That wait is at most 3 seconds (Ahmed): the setting's range 0–3000, the stored value 2000, and hub_turn_queue caps
--      what it reads at 3000.
-- No unit mode, licence, media switch or global switch changes. No phone number in this file.

update public.settings set value = '2000' where key = 'hub_burst_ms' and (value #>> '{}')::numeric > 3000;
`;

export function migration() {
  const get = (n) => fnFrom(SOURCES[n], n);
  let rg = get('internal.hub_setting_int_range');
  rg = edit(rg, 'range', `when 'hub_burst_ms' then array[0, 60000]`, `when 'hub_burst_ms' then array[0, 3000]`);
  let tq = get('public.hub_turn_queue');
  tq = edit(tq, 'queue', `v_burst integer := internal.hub_setting_int('hub_burst_ms', 4000);`,
    `-- at most 3 seconds (Ahmed, 15 Nov 2026 — the wait was the largest part of a reply's time)
  v_burst integer := least(greatest(internal.hub_setting_int('hub_burst_ms', 2000), 0), 3000);`);
  return [HEAD, '-- internal.hub_setting_int_range (20261115400000, copied): hub_burst_ms 0–3000', rg, '',
    '-- public.hub_turn_queue (20261115200000, copied): the burst capped at 3000 ms', tq, ''].join('\n');
}

if (process.argv[1]?.endsWith('hub-speed-migration.mjs')) {
  if (existsSync(OUT) && !process.argv.includes('--force')) {
    if (read(OUT_PATH) === migration()) {
      console.log(`✓ ${OUT_PATH} is current`);
      process.exit(0);
    }
    console.error(`${OUT_PATH} exists and differs — an applied migration is never edited (pass --force only before it is applied)`);
    process.exit(1);
  }
  writeFileSync(OUT, migration(), 'utf8');
  console.log(`✓ wrote ${OUT_PATH}`);
}
