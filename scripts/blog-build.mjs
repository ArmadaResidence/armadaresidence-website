// The articles published from the dashboard «المدونة» (3 Nov 2026, DECISIONS.md 2026-11-03 «Blog…») →
// content/articles.generated/<slug>.<lang>.md (gitignored) — the folder the `articles` collection reads
// (src/content.config.ts). Run by build.py before the Astro build.
//   1. BLOG_FIXTURE=<file.json> (checks: sample articles in the manifest's shape);
//   2. else public.blog_site_manifest (service role) when SUPABASE_SERVICE_ROLE_KEY is set — any failure is fatal then,
//      as for the photos and the offers (a build must never drop the published articles silently);
//   3. else the files of content/articles are copied as they are (the seed the migration imported), so a build without
//      the key renders the blog exactly as the dashboard's seed.
// Each article is written once per language it exists in (an article may exist in one language only), in the format of
// content/articles/README.md; the dashboard-only fields travel as extra frontmatter keys (excerpt, canonical, og_media,
// cover = media:… once a cover is published in «الصور» — src/lib/articles.ts resolves it from media.generated.json).
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = resolve(process.env.BLOG_OUT || join(ROOT, 'content', 'articles.generated'));
const SEED = join(ROOT, 'content', 'articles');
const KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || '';
const URL_ = (process.env.SUPABASE_URL || (process.env.PUBLIC_BOOKING_ENDPOINT || '').split('/functions/')[0]).replace(/\/$/, '');
const COVER_PENDING = '[TODO(photo)]';

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'README.md'), '# Generated by scripts/blog-build.mjs — do not edit. Source: the dashboard «المدونة» (seed: content/articles).\n');

let manifest;
let source;
if (process.env.BLOG_FIXTURE) {
  manifest = JSON.parse(readFileSync(resolve(process.env.BLOG_FIXTURE), 'utf8'));
  source = 'fixture';
} else if (KEY && URL_) {
  const res = await fetch(`${URL_}/rest/v1/rpc/blog_site_manifest`, {
    method: 'POST',
    headers: { apikey: KEY, Authorization: `Bearer ${KEY}`, 'Content-Type': 'application/json' },
    body: '{}',
  });
  if (!res.ok) {
    console.error(`blog-build: blog_site_manifest HTTP ${res.status} ${(await res.text()).slice(0, 200)}`);
    process.exit(1);
  }
  manifest = await res.json();
  source = 'supabase';
} else {
  let n = 0;
  for (const f of readdirSync(SEED)) {
    if (!/^[a-z0-9-]+\.(ar|en)\.md$/.test(f)) continue;
    cpSync(join(SEED, f), join(OUT, f));
    n++;
  }
  console.log(`NOTE: articles from the dashboard skipped (no SUPABASE_SERVICE_ROLE_KEY) — ${n} file(s) copied from content/articles`);
  process.exit(0);
}

// the same key order as content/articles, so a seeded article comes back byte for byte
const line = (k, v) => `${k}: ${Array.isArray(v) ? `[${v.map((x) => JSON.stringify(x)).join(', ')}]` : JSON.stringify(v)}`;
let files = 0;
const list = Array.isArray(manifest.articles) ? manifest.articles : [];
for (const a of list) {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(a.slug ?? '')) throw new Error(`blog-build: bad slug ${a.slug}`);
  for (const lang of a.langs ?? []) {
    const L = (k) => a[`${k}_${lang}`] ?? '';
    const fm = [
      line('author', a.author || 'Armada Residence'),
      line('status', 'published'),
      line('date', a.date_published),
      line('cover', a.cover_path || COVER_PENDING),
      line('cover_alt', L('cover_alt')),
      line('slug', a.slug),
      line('lang', lang),
      line('title', L('title')),
      line('seo_title', L('seo_title')),
      line('seo_description', L('seo_description')),
      line('tags', L('tags') || []),
      line('branch', a.branch ?? null),
      line('related_place', a.related_place ?? null),
    ];
    if (a.date_updated) fm.push(line('updated', a.date_updated));
    if (L('excerpt')) fm.push(line('excerpt', L('excerpt')));
    if (a.canonical) fm.push(line('canonical', a.canonical));
    if (a.og_media) fm.push(line('og_media', a.og_media));
    writeFileSync(join(OUT, `${a.slug}.${lang}.md`), `---\n${fm.join('\n')}\n---\n${L('body')}`);
    files++;
  }
}
console.log(`✓ articles (${source}): ${list.length} published article(s), ${files} page file(s)`);
