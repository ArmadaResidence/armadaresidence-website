// Guest Hub H10c (18 Nov 2026 — after the full production lab): the bank only. Writes
// supabase/migrations/20261118400000_guest_hub_h10c.sql: the corrections of tests/hub-bank/corrections.json whose
// migration is this one (h10-23: the stem «توافر», the right answer «يخضع للتوافر» was graded a miss). Run ONCE before the
// migration is applied; never after (CLAUDE.md §12) — then it only checks.
//   node scripts/hub-h10c-migration.mjs [--force]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
export const OUT_PATH = 'supabase/migrations/20261118400000_guest_hub_h10c.sql';
const OUT = new URL(`../${OUT_PATH}`, import.meta.url);
const sqlJson = (o) => JSON.stringify(o).replace(/":/g, '": ').replace(/,"/g, ', "').replace(/'/g, "''");

export function migration() {
  const all = JSON.parse(read('tests/hub-bank/corrections.json')).items;
  const corr = Object.entries(all).filter(([, c]) => c.migration === OUT_PATH.split('/').pop())
    .map(([id, c]) => `update public.hub_test_items\n   set expect = '${sqlJson(c.expect)}'::jsonb\n where key = '${id}' and expect = '${sqlJson(c.old)}'::jsonb;`).join('\n');
  return `-- Guest Hub H10c (18 Nov 2026 — DECISIONS.md 2026-11-18 «Guest Hub H10»): after the full production lab, the bank's
-- corrections only. Generated by scripts/hub-h10c-migration.mjs — never edited once applied (CLAUDE.md §12). Every UPDATE
-- carries a WHERE.

${corr}
`;
}

const isMain = process.argv[1] && new URL(import.meta.url).pathname.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop());
if (isMain) {
  const out = migration();
  if (existsSync(OUT) && !process.argv.includes('--force')) {
    if (readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') !== out) {
      console.error(`${OUT_PATH} differs from its generator — never regenerate an applied migration (CLAUDE.md §12)`);
      process.exit(1);
    }
    console.log(`✓ ${OUT_PATH} = its generator`);
  } else {
    writeFileSync(OUT, out, 'utf8');
    console.log(`✓ wrote ${OUT_PATH}`);
  }
}
