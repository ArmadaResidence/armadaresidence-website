"""Phase 2a seed (DECISIONS.md 2026-10-25): writes supabase/migrations/20261025000100_phase2a_seed.sql from content/.

content/*.json stays the source of truth for the first import only (CLAUDE.md §9b): branches, room types (names,
capacity, extra_beds_max, bookable, base rate = rooms.json base_price — Q6) and the pricing settings from pricing.json.
Every insert is ON CONFLICT DO NOTHING, so re-running never overwrites what the dashboard changed since. Both
per-branch switches are seeded OFF. Run: python scripts/supabase-seed.py (then push with the Supabase CLI).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "supabase" / "migrations" / "20261025000100_phase2a_seed.sql"


def load(name):
    return json.loads((ROOT / "content" / name).read_bytes().decode("utf-8"))


def q(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def main():
    branches = load("branches.json")["branches"]
    rooms = load("rooms.json")["rooms"]
    pricing = load("pricing.json")
    slugs = [b["slug"] for b in branches]

    bf = pricing["breakfast"]
    kids = pricing["children"]["breakfast"]
    adult = bf["addon_price_per_person"]
    # pricing.json child ladder: up_to_5 / 6_to_12 / 13_plus (13+ = the adult price)
    assert set(kids) == {"up_to_5", "6_to_12", "13_plus"}, kids
    assert kids["13_plus"] == adult, "13_plus must equal the adult breakfast price"
    settings = {
        "breakfast": {"adult": adult, "child_tiers": [{"max_age": 5, "price": kids["up_to_5"]}, {"max_age": 12, "price": kids["6_to_12"]}]},
        "extra_bed_per_night": pricing["extra_bed_per_night"],
        "instant_booking": {s: False for s in slugs},
        "show_prices": {s: False for s in slugs},
        "instant_limits": {"same_day_cutoff": "20:00", "max_nights": 30},
    }

    lines = [
        "-- GENERATED by scripts/supabase-seed.py from content/ — do not edit by hand (DECISIONS.md 2026-10-25).",
        "-- First import of branches, room types and pricing settings. ON CONFLICT DO NOTHING: dashboard edits are never",
        "-- overwritten. Both per-branch switches start OFF. No guest data, no recipient address, no user.",
        "select set_config('app.actor', 'seed', true);",
        "",
        "insert into public.branches (slug, name_ar, name_en, sort) values",
        ",\n".join(f"  ({q(b['slug'])}, {q(b['name_ar'])}, {q(b['name_en'])}, {i})" for i, b in enumerate(branches)),
        "on conflict (slug) do nothing;",
        "",
        "insert into public.room_types (branch, slug, name_ar, name_en, capacity, extra_beds_max, bookable, base_rate, sort, active) values",
    ]
    rows = []
    for i, r in enumerate(rooms):
        assert r["branch"] in slugs, r["slug"]
        bookable = r.get("availability") != "sold_out" and r.get("show_on_site", True) and r.get("active", True)
        rows.append(
            f"  ({q(r['branch'])}, {q(r['slug'])}, {q(r['name_ar'])}, {q(r['name_en'])}, {int(r['capacity'])}, "
            f"{int(r.get('extra_beds_max', 0))}, {q(bool(bookable))}, {q(r.get('base_price'))}, {i}, {q(bool(r.get('active', True)))})"
        )
    lines += [",\n".join(rows), "on conflict (branch, slug) do nothing;", ""]
    lines.append("insert into public.settings (key, value) values")
    lines.append(",\n".join(f"  ({q(k)}, {q(json.dumps(v, ensure_ascii=False))}::jsonb)" for k, v in settings.items()))
    lines.append("on conflict (key) do nothing;")
    OUT.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(branches)} branches, {len(rooms)} room types, {len(settings)} settings")


if __name__ == "__main__":
    main()
