// The FAQ published from the dashboard «الأسئلة الشائعة» (3 Nov 2026, DECISIONS.md 2026-11-03 «FAQ…») →
// content/faq.generated.json (gitignored), read by src/lib/faq.ts. Run by build.py before the Astro build.
//   1. FAQ_FIXTURE=<file.json> (checks: the manifest's shape);
//   2. else public.faq_site_manifest (service role) when SUPABASE_SERVICE_ROLE_KEY is set — any failure is fatal then,
//      as for the photos (a build must never drop the published FAQ silently);
//   3. else content/faq.json (the dashboard's seed, approved by Ahmed on 2 Nov 2026) in the manifest's shape.
// {breakfast} / {extra_bed} stay as they are here: the page fills them from the pricing settings (content.ts → withFees).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DATA = resolve(process.env.FAQ_DATA || join(ROOT, 'content', 'faq.generated.json'));
const KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || '';
const URL_ = (process.env.SUPABASE_URL || (process.env.PUBLIC_BOOKING_ENDPOINT || '').split('/functions/')[0]).replace(/\/$/, '');
const NOTE = 'Generated by scripts/faq-build.mjs from the FAQ published in the dashboard «الأسئلة الشائعة». Do not edit.';
const CATEGORIES = ['booking', 'stay', 'branches', 'business'];

let items;
let source;
if (process.env.FAQ_FIXTURE) {
  items = JSON.parse(readFileSync(resolve(process.env.FAQ_FIXTURE), 'utf8')).items;
  source = 'fixture';
} else if (KEY && URL_) {
  const res = await fetch(`${URL_}/rest/v1/rpc/faq_site_manifest`, {
    method: 'POST',
    headers: { apikey: KEY, Authorization: `Bearer ${KEY}`, 'Content-Type': 'application/json' },
    body: '{}',
  });
  if (!res.ok) {
    console.error(`faq-build: faq_site_manifest HTTP ${res.status} ${(await res.text()).slice(0, 200)}`);
    process.exit(1);
  }
  items = (await res.json()).items;
  source = 'supabase';
} else {
  const seed = JSON.parse(readFileSync(join(ROOT, 'content', 'faq.json'), 'utf8'));
  items = seed.items.map((i, n) => ({ key: i.id, category: i.category, q_ar: i.q_ar, q_en: i.q_en, a_ar: i.a_ar, a_en: i.a_en, sort: n, hidden: false }));
  source = 'faq.json';
}
if (!Array.isArray(items)) {
  console.error('faq-build: the manifest has no items list');
  process.exit(1);
}
for (const i of items) {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(i.key) || !CATEGORIES.includes(i.category) || !i.q_ar || !i.q_en || !i.a_ar || !i.a_en) {
    console.error(`faq-build: an item is incomplete (${i.key})`);
    process.exit(1);
  }
}
writeFileSync(DATA, JSON.stringify({ _note: NOTE, source, items: items.filter((i) => !i.hidden) }, null, 1) + '\n');
console.log(`✓ faq (${source}): ${items.length} question(s)`);
