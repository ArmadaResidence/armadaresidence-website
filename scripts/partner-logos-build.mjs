// The partner logos published from the dashboard «شعارات الشركاء» (7 Nov 2026) → the files the home page's logo strip
// shows: public/images/partner-logos/<id8>-<sha8>.svg|png (gitignored, rewritten on every run) and
// content/partner-logos.generated.json (gitignored). Run by build.py right after scripts/reviews-build.mjs.
//   1. PARTNER_LOGOS_FIXTURE=<file.json> (checks: the manifest's shape — scripts/fixtures/partner-logos-sample.json);
//   2. else public.partner_logos_site_manifest (service role) when SUPABASE_SERVICE_ROLE_KEY is set — any failure is
//      fatal then, as for the reviews (a build must never drop the published logos silently);
//   3. else content/partner-logos.json (the dashboard's seed; empty — no partner logos existed before 7 Nov 2026).
// Every logo is checked again here, whatever its source: an SVG through the strict allow-list below (the same rules as
// internal.partner_logo_svg_ok and admin/src/lib/partner-logos.ts: no script, no on* attribute, no external href /
// xlink:href / url(), no foreignObject or any element outside the list, ≤ 200 KB); a PNG by its signature, its IHDR
// size = the stated size, ≤ 300 KB. A logo that fails, or one without both alt texts, stops the build.
// The generated file: { _note, source, items: [{ id, alt_ar, alt_en, src, width, height }] } in the dashboard's order;
// `src` is the site path without the review site's sub-path (the page adds its base).
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DATA = resolve(process.env.PARTNER_LOGOS_DATA || join(ROOT, 'content', 'partner-logos.generated.json'));
const OUT = resolve(process.env.PARTNER_LOGOS_DIR || join(ROOT, 'public', 'images', 'partner-logos'));
const WEB = '/images/partner-logos';
const KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || '';
const URL_ = (process.env.SUPABASE_URL || (process.env.PUBLIC_BOOKING_ENDPOINT || '').split('/functions/')[0]).replace(/\/$/, '');
const NOTE = 'Generated by scripts/partner-logos-build.mjs from the logos published in the dashboard «شعارات الشركاء». Do not edit.';
const SVG_MAX = 200 * 1024;
const PNG_MAX = 300 * 1024;
const PNG_SIG = '89504e470d0a1a0a';
/** the SVG elements a logo may use (filter primitives fe* as well) — the same list as the database and the dashboard */
const SVG_ELEMENTS = ['svg', 'g', 'path', 'rect', 'circle', 'ellipse', 'line', 'polyline', 'polygon', 'text', 'tspan', 'textpath', 'defs',
  'lineargradient', 'radialgradient', 'stop', 'clippath', 'mask', 'pattern', 'use', 'symbol', 'title', 'desc', 'style', 'filter', 'marker'];

/** null when the SVG passes, else the reason */
function svgProblem(s) {
  if (typeof s !== 'string' || !s.trim()) return 'empty';
  if (Buffer.byteLength(s, 'utf8') > SVG_MAX) return 'larger than 200 KB';
  if (!/^\s*(<\?xml[^>]*\?>\s*)?(<!--[\s\S]*?-->\s*)*<svg[\s>]/i.test(s)) return 'does not start with <svg>';
  if (!/<\/svg>\s*$/i.test(s)) return 'does not end with </svg>';
  if (/<script|<foreignobject|<iframe|<embed|<object|<!entity|<!doctype|javascript:|data:text|\son[a-z]+\s*=/i.test(s)) return 'a script, an event handler, an embedded document or an entity';
  if (/(xlink:)?href\s*=\s*["'](?!#)/i.test(s)) return 'an external href';
  if (/url\(\s*["']?(?!#)/i.test(s)) return 'an external url()';
  if (/@import/i.test(s)) return '@import';
  for (const m of s.matchAll(/<([A-Za-z][A-Za-z0-9:._-]*)/g)) {
    const e = m[1].toLowerCase();
    if (!SVG_ELEMENTS.includes(e) && !/^fe[a-z]+$/.test(e)) return `the element <${m[1]}>`;
  }
  return null;
}

/** the PNG's bytes and IHDR size, or the reason it is not one */
function pngOf(b64) {
  const s = typeof b64 === 'string' ? b64.replace(/\s+/g, '') : '';
  if (!s || !/^[A-Za-z0-9+/]+={0,2}$/.test(s) || s.length % 4 !== 0) return { problem: 'not base64' };
  const bytes = Buffer.from(s, 'base64');
  if (bytes.length > PNG_MAX) return { problem: 'larger than 300 KB' };
  if (bytes.length < 33 || bytes.subarray(0, 8).toString('hex') !== PNG_SIG || bytes.subarray(12, 16).toString('latin1') !== 'IHDR') return { problem: 'not a PNG' };
  return { bytes, width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
}

const fatal = (msg) => {
  console.error(`partner-logos-build: ${msg}`);
  process.exit(1);
};

let items;
let source;
if (process.env.PARTNER_LOGOS_FIXTURE) {
  items = JSON.parse(readFileSync(resolve(process.env.PARTNER_LOGOS_FIXTURE), 'utf8')).items;
  source = 'fixture';
} else if (KEY && URL_) {
  const res = await fetch(`${URL_}/rest/v1/rpc/partner_logos_site_manifest`, {
    method: 'POST',
    headers: { apikey: KEY, Authorization: `Bearer ${KEY}`, 'Content-Type': 'application/json' },
    body: '{}',
  });
  if (!res.ok) fatal(`partner_logos_site_manifest HTTP ${res.status} ${(await res.text()).slice(0, 200)}`);
  items = (await res.json()).items;
  source = 'supabase';
} else {
  const seed = JSON.parse(readFileSync(join(ROOT, 'content', 'partner-logos.json'), 'utf8'));
  items = (seed.items ?? []).map((r, n) => ({ ...r, sort: r.sort ?? n }));
  source = 'partner-logos.json';
}
if (!Array.isArray(items)) fatal('the manifest has no items list');

const shown = items.filter((r) => r.show_home !== false).map((r, n) => ({ r, n })).sort((a, b) => (a.r.sort ?? 0) - (b.r.sort ?? 0) || a.n - b.n).map((x) => x.r);
rmSync(OUT, { recursive: true, force: true });
const out = [];
for (const r of shown) {
  const label = `${r.name_en || r.name_ar || '?'} (${r.id ?? '?'})`;
  if (typeof r.id !== 'string' || !/^[A-Za-z0-9-]{8,64}$/.test(r.id)) fatal(`a logo without a valid id: ${label}`);
  const altAr = typeof r.name_ar === 'string' ? r.name_ar.trim() : '';
  const altEn = typeof r.name_en === 'string' ? r.name_en.trim() : '';
  if (!altAr || !altEn) fatal(`a logo without both alt texts: ${label}`);
  if (!Number.isInteger(r.width) || !Number.isInteger(r.height) || r.width < 1 || r.height < 1 || r.width > 4000 || r.height > 4000) fatal(`a logo without a valid size: ${label}`);
  let bytes;
  let ext;
  if (r.kind === 'svg') {
    const why = svgProblem(r.data);
    if (why) fatal(`the SVG of ${label} is refused: ${why}`);
    bytes = Buffer.from(r.data.trim(), 'utf8');
    ext = 'svg';
  } else if (r.kind === 'png') {
    const png = pngOf(r.data);
    if (png.problem) fatal(`the PNG of ${label} is refused: ${png.problem}`);
    if (png.width !== r.width || png.height !== r.height) fatal(`the PNG of ${label} is ${png.width} × ${png.height}, not ${r.width} × ${r.height}`);
    bytes = png.bytes;
    ext = 'png';
  } else fatal(`a logo of an unknown kind: ${label}`);
  const file = `${r.id.replace(/-/g, '').slice(0, 8).toLowerCase()}-${createHash('sha256').update(bytes).digest('hex').slice(0, 8)}.${ext}`;
  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, file), bytes);
  out.push({ id: r.id, alt_ar: altAr, alt_en: altEn, src: `${WEB}/${file}`, width: r.width, height: r.height });
}
writeFileSync(DATA, JSON.stringify({ _note: NOTE, source, items: out }, null, 1) + '\n');
console.log(`✓ partner logos (${source}): ${out.length} on the home page`);
