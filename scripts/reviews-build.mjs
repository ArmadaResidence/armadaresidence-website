// The guest reviews published from the dashboard «آراء الضيوف» (7 Nov 2026, DECISIONS.md 2026-11-07 «Home sections») →
// content/reviews.generated.json (gitignored), read by src/lib/reviews.ts. Run by build.py before the Astro build.
//   1. REVIEWS_FIXTURE=<file.json> (checks: the manifest's shape);
//   2. else public.reviews_site_manifest (service role) when SUPABASE_SERVICE_ROLE_KEY is set — any failure is fatal then,
//      as for the FAQ (a build must never drop the published reviews silently);
//   3. else content/reviews.json (the dashboard's seed, approved by Ahmed on 7 Nov 2026) in the manifest's shape.
// Only the reviews shown on the home page reach the file, in the dashboard's order.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DATA = resolve(process.env.REVIEWS_DATA || join(ROOT, 'content', 'reviews.generated.json'));
const KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || '';
const URL_ = (process.env.SUPABASE_URL || (process.env.PUBLIC_BOOKING_ENDPOINT || '').split('/functions/')[0]).replace(/\/$/, '');
const NOTE = 'Generated by scripts/reviews-build.mjs from the reviews published in the dashboard «آراء الضيوف». Do not edit.';
const BRANCHES = ['airport-road', 'shafa-road'];

let items;
let source;
if (process.env.REVIEWS_FIXTURE) {
  items = JSON.parse(readFileSync(resolve(process.env.REVIEWS_FIXTURE), 'utf8')).items;
  source = 'fixture';
} else if (KEY && URL_) {
  const res = await fetch(`${URL_}/rest/v1/rpc/reviews_site_manifest`, {
    method: 'POST',
    headers: { apikey: KEY, Authorization: `Bearer ${KEY}`, 'Content-Type': 'application/json' },
    body: '{}',
  });
  if (!res.ok) {
    console.error(`reviews-build: reviews_site_manifest HTTP ${res.status} ${(await res.text()).slice(0, 200)}`);
    process.exit(1);
  }
  items = (await res.json()).items;
  source = 'supabase';
} else {
  const seed = JSON.parse(readFileSync(join(ROOT, 'content', 'reviews.json'), 'utf8'));
  items = seed.items.map((r, n) => ({ ...r, sort: n }));
  source = 'reviews.json';
}
if (!Array.isArray(items)) {
  console.error('reviews-build: the manifest has no items list');
  process.exit(1);
}
for (const r of items) {
  const ok = typeof r.first_name === 'string' && r.first_name.trim() && BRANCHES.includes(r.branch) && Number.isInteger(r.stars) && r.stars >= 1 && r.stars <= 5
    && (r.lang === 'ar' || r.lang === 'en') && typeof r.text === 'string' && r.text.trim() && /^https:\/\/[^\s"<>]+$/.test(r.source_url ?? '');
  if (!ok) {
    console.error(`reviews-build: a review is incomplete (${r.first_name ?? '?'} · ${r.branch ?? '?'})`);
    process.exit(1);
  }
}
const shown = items.filter((r) => r.show_home !== false).sort((a, b) => (a.sort ?? 0) - (b.sort ?? 0));
writeFileSync(DATA, JSON.stringify({ _note: NOTE, source, items: shown }, null, 1) + '\n');
console.log(`✓ reviews (${source}): ${shown.length} on the home page`);
