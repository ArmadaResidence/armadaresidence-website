// «المحتوى والظهور» (3 Nov 2026, DECISIONS.md 2026-11-03 «Content & visibility…») → content/content.generated.json
// (gitignored): the texts published from the dashboard (file, JSON paths, anchors, ar / en), what is hidden from the site
// (branches, room types, sections) and the announcement bar's published announcements. Run FIRST by build.py: the texts
// are applied to the content before it is validated, before the functions' content is generated and before the pages
// are built (src/lib/content.ts, astro.config.mjs — the redirects of hidden pages — and qa.py read the same file).
//   1. CONTENT_FIXTURE=<file.json> (checks: a manifest's shape); else the `announcement` of OFFERS_FIXTURE (the offers
//      sample's bar, scripts/fixtures/offers-sample.json);
//   2. else public.content_site_manifest (service role) when SUPABASE_SERVICE_ROLE_KEY is set — any failure is fatal then
//      (a build must never drop a published text or show a hidden page silently);
//   3. else { source: 'none' }: nothing applied, nothing hidden, no bar — the content files as they are.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DATA = resolve(process.env.CONTENT_DATA || join(ROOT, 'content', 'content.generated.json'));
const KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || '';
const URL_ = (process.env.SUPABASE_URL || (process.env.PUBLIC_BOOKING_ENDPOINT || '').split('/functions/')[0]).replace(/\/$/, '');
const NOTE = 'Generated by scripts/content-build.mjs from «المحتوى والظهور» (texts, visibility, the announcement bar). Do not edit.';
const EMPTY = { texts: [], hidden: { branches: [], rooms: [], sections: [] }, announcements: [] };
const write = (o) => writeFileSync(DATA, JSON.stringify({ _note: NOTE, ...EMPTY, ...o }, null, 1) + '\n');

let manifest = null;
let source = 'none';
if (process.env.CONTENT_FIXTURE) {
  manifest = JSON.parse(readFileSync(resolve(process.env.CONTENT_FIXTURE), 'utf8'));
  source = 'fixture';
} else if (process.env.OFFERS_FIXTURE) {
  const o = JSON.parse(readFileSync(resolve(process.env.OFFERS_FIXTURE), 'utf8'));
  manifest = { announcements: o.announcement ? [o.announcement] : [], today: o.today ?? null };
  source = 'fixture';
} else if (KEY && URL_) {
  const res = await fetch(`${URL_}/rest/v1/rpc/content_site_manifest`, {
    method: 'POST',
    headers: { apikey: KEY, Authorization: `Bearer ${KEY}`, 'Content-Type': 'application/json' },
    body: '{}',
  });
  if (!res.ok) {
    console.error(`content-build: content_site_manifest HTTP ${res.status} ${(await res.text()).slice(0, 200)}`);
    process.exit(1);
  }
  manifest = await res.json();
  source = 'supabase';
}
if (!manifest) {
  write({ source: 'none' });
  console.log('NOTE: «المحتوى والظهور» skipped (no SUPABASE_SERVICE_ROLE_KEY) — the content files as they are, nothing hidden, no bar');
  process.exit(0);
}
const hidden = { ...EMPTY.hidden, ...(manifest.hidden ?? {}) };
const texts = Array.isArray(manifest.texts) ? manifest.texts : [];
for (const t of texts) {
  if (!t.file || !Array.isArray(t.path_ar) || !Array.isArray(t.path_en) || typeof t.ar !== 'string' || typeof t.en !== 'string') {
    console.error(`content-build: a published text is incomplete (${t.key})`);
    process.exit(1);
  }
}
write({ source, at: manifest.at ?? new Date().toISOString(), today: manifest.today ?? null, texts, hidden, announcements: Array.isArray(manifest.announcements) ? manifest.announcements : [] });
console.log(`✓ content (${source}): ${texts.length} published text(s); hidden: ${[...hidden.branches, ...hidden.rooms, ...hidden.sections].join(', ') || 'none'}; ${(manifest.announcements ?? []).length} announcement(s)`);
