// Guest Hub H6 pass 5 (15 Nov 2026): writes supabase/migrations/20261115100000_guest_hub_conversation.sql from
//   - the last definition of public.hub_turn_claim (20261114900000_guest_hub_pass4.sql), its history window 6 → 12 messages
//     (Ahmed: understanding and composing get at least the last 10 messages of the episode);
//   - tests/hub-bank/conversations.jsonl — the conversation bank as test-lab items (tag «conversation»);
//   - the seven production test questions of 14 Nov that asked for the old fixed small-talk lines word for word;
//   - the two «لم أعرف الإجابة» entries of one-character messages since go-live (now a clarifying question).
// Run ONCE before the migration is applied; an applied migration is never edited (CLAUDE.md §12). scripts/hub-eval-check.mjs
// checks that the migration's bank equals the file.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const OUT = new URL('../supabase/migrations/20261115100000_guest_hub_conversation.sql', import.meta.url);
if (existsSync(OUT) && !process.argv.includes('--force')) {
  console.error('hub-conv-migration: the migration exists — an applied migration is never edited (pass --force only before it is applied)');
  process.exit(2);
}
const P4 = read('supabase/migrations/20261114900000_guest_hub_pass4.sql');
const a = P4.indexOf('create or replace function public.hub_turn_claim(p_turn uuid)');
const b = P4.indexOf('\n$$;', a) + 4;
let claim = P4.slice(a, b);
if (!claim.includes('order by m.sent_at desc limit 6) h)')) throw new Error('hub_turn_claim: the history window was not found');
claim = claim.replace('order by m.sent_at desc limit 6) h)', 'order by m.sent_at desc limit 12) h)');

const conv = read('tests/hub-bank/conversations.jsonl').split('\n').filter((l) => l.trim()).map((l) => JSON.parse(l)).filter((x) => !x._header);
const rows = conv.map((c) => ({ key: c.id, unit: c.unit, language: c.language, messages: c.messages, expect: c.expect, note: c.note ?? null, tags: c.tags ?? ['conversation'] }));
const bank = JSON.stringify(rows);
if (bank.includes('$conv_bank$')) throw new Error('the bank holds the dollar-quote tag');

const sql = `-- Guest Hub H6 pass 5 (15 Nov 2026, Ahmed — DECISIONS.md 2026-11-15 «Guest Hub: natural conversation policy»).
-- Generated by scripts/hub-conv-migration.mjs — never edited once applied (a fix is a new migration).
--   1. hub_turn_claim: the episode's last 12 messages to the model (was 6) — a follow-up («طيب والأطفال؟») resolves
--      against the answer before it. Nothing else in the function changes.
--   2. The conversation bank (tests/hub-bank/conversations.jsonl) as test-lab items: multi-turn, one expectation per
--      guest message (grade.ts gradeConversation), tag «conversation»; shown in «مختبر الاختبار» beside the questions.
--   3. The seven test questions of 14 Nov (production only) that asked for the old FIXED small-talk lines word for word:
--      small talk is now written by the model, so they keep what the policy guarantees («وعليكم السلام», the greeting
--      line added by code, a reply) and drop the exact wording.
--   4. «لم أعرف الإجابة»: the two system entries of one-character messages since go-live («اا», «؟») dismissed — under
--      this policy such a message gets one clarifying question and is never a gap. A real request is kept.
-- One audit batch (actor «H6 pass 5 — migration, Ahmed's OK»). No unit mode, licence or switch changes.

-- ── 1 ──
${claim}

-- ── 2, 3, 4 ──
do $$
declare
  v_batch uuid := internal.begin_batch();
  v_sort integer;
begin
  perform set_config('app.actor', 'H6 pass 5 — migration, Ahmed''s OK', true);
  v_sort := coalesce((select max(x.sort) + 1 from public.hub_test_items x), 0);
  insert into public.hub_test_items (key, unit_key, language, messages, expect, note, tags, added_from, sort)
  select e ->> 'key', e ->> 'unit', e ->> 'language', e -> 'messages', e -> 'expect', e ->> 'note',
         array(select jsonb_array_elements_text(e -> 'tags')), 'seed', v_sort + (o - 1)::integer
    from jsonb_array_elements($conv_bank$${bank}$conv_bank$::jsonb) with ordinality as x(e, o)
  on conflict (key) do nothing;

  update public.hub_test_items set expect = '{"action": "greeting", "must_include": ["وعليكم السلام، مرحبًا بك في"]}'::jsonb
   where key in ('s-salaam-airport', 's-salaam-shafa') and expect ->> 'action' = 'greeting';
  update public.hub_test_items set expect = '{"action": "greeting", "must_include": ["وعليكم السلام"]}'::jsonb
   where key in ('s-salaam-again-airport', 's-salaam-again-shafa') and expect ->> 'action' = 'greeting';
  update public.hub_test_items set expect = '{"action": "greeting"}'::jsonb
   where key in ('s-thanks-airport', 's-thanks-shafa-en', 's-hello-again-airport-en') and expect ->> 'action' = 'greeting';

  update public.hub_unanswered
     set status = 'dismissed', dismiss_reason = 'محادثة عادية — سؤال توضيحي (H6 pass 5)', resolved_at = now()
   where id in ('5b240cc6-6e7d-4c90-b1a6-c1df49f326c2', 'efad35cc-a754-434a-9d7e-dfffd91b07df') and status = 'open';
end;
$$;
`;
writeFileSync(OUT, sql);
console.log(`✓ wrote ${OUT.pathname.split('/').slice(-1)[0]} — ${rows.length} conversations`);
