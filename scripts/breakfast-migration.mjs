// Breakfast fees (15 Nov 2026, Ahmed — DECISIONS.md 2026-11-15 «Breakfast fees»): writes
// supabase/migrations/20261115300000_breakfast_fees.sql from the latest definitions it replaces (each copied with exact
// edits that must match once) and the new breakfast texts of content/faq.json and content/policies.json. Run ONCE before
// the migration is applied; an applied migration is never edited (CLAUDE.md §12).
//   node scripts/breakfast-migration.mjs [--force]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fnFrom } from './hub-team-migration.mjs';

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
export const OUT_PATH = 'supabase/migrations/20261115300000_breakfast_fees.sql';
const OUT = new URL(`../${OUT_PATH}`, import.meta.url);
const edit = (fn, from, to) => {
  if (fn.split(from).length !== 2) throw new Error(`an edit matched ${fn.split(from).length - 1} times — ${from.slice(0, 80)}`);
  return fn.replace(from, () => to);
};
const q = (s) => {
  if (s.includes('$bf$')) throw new Error('a dollar-quote tag inside a text');
  return `$bf$${s}$bf$`;
};

export function migration() {
  const faq = JSON.parse(read('content/faq.json')).items.find((x) => x.id === 'breakfast');
  const pol = JSON.parse(read('content/policies.json')).page.sections.find((x) => x.id === 'guests');
  let site = fnFrom('supabase/migrations/20261102000100_dining.sql', 'public.site_fees');
  site = edit(site, `    'extra_bed_per_night', (select (s.value #>> '{}')::numeric from public.settings s where s.key = 'extra_bed_per_night'))`,
    `    'extra_bed_per_night', (select (s.value #>> '{}')::numeric from public.settings s where s.key = 'extra_bed_per_night'),
    -- the children's breakfast (15 Nov 2026): [{max_age, price}] — the texts are generated from it, never typed
    'breakfast_child_tiers', (select s.value -> 'child_tiers' from public.settings s where s.key = 'breakfast'))`);
  let cp = fnFrom('supabase/migrations/20261107200000_texts_session.sql', 'internal.copy_problems');
  cp = edit(cp, `if v_ph not in ('breakfast', 'extra_bed',`, `if v_ph not in ('breakfast', 'extra_bed', 'breakfast_free_age', 'breakfast_child_age', 'breakfast_child',`);
  return `-- Breakfast fees (15 Nov 2026, Ahmed — DECISIONS.md 2026-11-15 «Breakfast fees»). Generated by scripts/breakfast-migration.mjs.
-- Settings is the source: adult 25 SAR per person per day incl. VAT; children up to 6 free, up to 12 SAR 12.50, above 12
-- the adult price. The texts are generated from Settings, never typed:
--   1. site_fees() also returns breakfast_child_tiers (the build writes it to content/fees.generated.json);
--   2. internal.hub_fill_fees (the assistant's FAQ read) fills {breakfast_free_age}, {breakfast_child_age} and
--      {breakfast_child} by the same rule as the site (src/lib/content.ts → breakfastChildren);
--   3. internal.copy_problems accepts the three placeholders (the dashboard's FAQ and content editors);
--   4. the published FAQ answer «breakfast» and the content field policy.guests.body (seed and draft) take the new texts
--      of content/faq.json and content/policies.json. One audit batch. No unit mode, licence or switch changes.

${site.replace('create or replace function public.site_fees() returns jsonb', 'create or replace function public.site_fees() returns jsonb')}

create or replace function internal.hub_fill_fees(p text, p_lang text) returns text
language sql stable security definer set search_path = '' as $$
  with f as (select public.site_fees() as j),
       t as (select (x ->> 'max_age')::numeric as age, (x ->> 'price')::numeric as price
               from f, jsonb_array_elements(coalesce(f.j -> 'breakfast_child_tiers', '[]'::jsonb)) x),
       k as (select (select max(age) from t where price = 0) as free_age,
                    (select age from t where price > 0 order by age limit 1) as child_age,
                    (select price from t where price > 0 order by age limit 1) as child_price)
  select replace(replace(replace(replace(replace(coalesce(p, ''),
    '{breakfast}', coalesce(internal.hub_sar_text((f.j ->> 'breakfast_adult')::numeric, p_lang), '{breakfast}')),
    '{extra_bed}', coalesce(internal.hub_sar_text((f.j ->> 'extra_bed_per_night')::numeric, p_lang), '{extra_bed}')),
    '{breakfast_free_age}', coalesce(k.free_age::bigint::text, '{breakfast_free_age}')),
    '{breakfast_child_age}', coalesce(k.child_age::bigint::text, '{breakfast_child_age}')),
    '{breakfast_child}', coalesce(internal.hub_sar_text(k.child_price, p_lang), '{breakfast_child}'))
    from f, k
$$;

${cp}

do $bfm$
declare v_batch uuid := internal.begin_batch();
begin
  perform set_config('app.actor', 'Breakfast fees — migration, Ahmed''s brief of 15 Nov 2026', true);
  update public.faq_items
     set a_ar = ${q(faq.a_ar)}, a_en = ${q(faq.a_en)},
         live = case when live is not null then live || jsonb_build_object('a_ar', ${q(faq.a_ar)}, 'a_en', ${q(faq.a_en)}) end
   where key = 'breakfast' and not is_test;
  update public.content_fields
     set seed_ar = ${q(pol.body_ar)}, seed_en = ${q(pol.body_en)},
         draft_ar = case when draft_ar is null or draft_ar = seed_ar then ${q(pol.body_ar)} else draft_ar end,
         draft_en = case when draft_en is null or draft_en = seed_en then ${q(pol.body_en)} else draft_en end
   where key = 'policy.guests.body';
end;
$bfm$;
`;
}

if (process.argv[1]?.endsWith('breakfast-migration.mjs')) {
  if (existsSync(OUT) && !process.argv.includes('--force') && read(OUT_PATH) !== migration()) {
    console.error(`${OUT_PATH} exists and differs — an applied migration is never edited`);
    process.exit(1);
  }
  writeFileSync(OUT, migration(), 'utf8');
  console.log(`✓ wrote ${OUT_PATH}`);
}
