// Tiny blurred previews (LQIP) for the approved photos: every content/images/**/*-800.webp → a 16 px WebP data URI
// in content/lqip.json (keyed by the public path, e.g. "/images/dining/caesar-salad-800.webp"). Run by build.py;
// Photo.astro paints the preview under the real image while it loads (item 13, 11 Oct 2026). ≈ 300 bytes each.
//   node scripts/lqip.mjs [site root]   (default: this repository; scripts/photos-import.mjs passes its --site)
import sharp from 'sharp';
import { readdirSync, statSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = process.argv[2] || fileURLToPath(new URL('..', import.meta.url));
const SRC = join(ROOT, 'content', 'images');
const OUT = join(ROOT, 'content', 'lqip.json');

function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (/-800\.webp$/.test(name)) acc.push(p);
  }
  return acc;
}

const files = existsSync(SRC) ? walk(SRC) : [];
const prev = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')) : {};
const out = { _note: 'Generated by scripts/lqip.mjs from content/images (16 px blurred previews, base64 WebP). Do not edit.' };
for (const f of files.sort()) {
  const key = '/images/' + relative(SRC, f).split(sep).join('/');
  const buf = await sharp(f).resize(16).webp({ quality: 40 }).toBuffer();
  out[key] = `data:image/webp;base64,${buf.toString('base64')}`;
}
const changed = JSON.stringify(prev) !== JSON.stringify(out);
if (changed) writeFileSync(OUT, JSON.stringify(out, null, 1) + '\n');
console.log(`✓ lqip: ${files.length} previews in content/lqip.json${changed ? '' : ' (unchanged)'}`);
