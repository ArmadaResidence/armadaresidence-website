// The offers published from the dashboard «العروض» (2 Nov 2026, DECISIONS.md 2026-11-02 «Offers…») → content/offers.generated.json
// (gitignored), read by src/lib/content.ts. Run by build.py before the Astro build.
//   1. OFFERS_FIXTURE=<file.json> (checks: sample offers + a pop-up, the shape of the manifest), else <MEDIA_FIXTURE>/offers.json
//      when the media sample carries one;
//   2. else public.offers_site_manifest (service role) when SUPABASE_SERVICE_ROLE_KEY is set — any failure is fatal then,
//      as for the photos (a build must never drop the published offers silently);
//   3. else { source: 'none' }: src/lib/content.ts falls back to content/offers.json (the two sales sections the
//      migration seeded as the b2b offers), so a build without the key renders /offers/ exactly as the dashboard's seed.
// The manifest holds every live offer that has not ended; the pages drop the ones that start later (content.ts) and the
// daily scheduled build brings them in.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DATA = resolve(process.env.OFFERS_DATA || join(ROOT, 'content', 'offers.generated.json'));
const KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || '';
const URL_ = (process.env.SUPABASE_URL || (process.env.PUBLIC_BOOKING_ENDPOINT || '').split('/functions/')[0]).replace(/\/$/, '');
const NOTE = 'Generated by scripts/offers-build.mjs from the offers published in the dashboard «العروض». Do not edit.';
const write = (o) => writeFileSync(DATA, JSON.stringify({ _note: NOTE, ...o }, null, 1) + '\n');

const mediaFixture = process.env.MEDIA_FIXTURE ? join(resolve(process.env.MEDIA_FIXTURE), 'offers.json') : '';
const fixture = process.env.OFFERS_FIXTURE || (mediaFixture && existsSync(mediaFixture) ? mediaFixture : '');
let manifest;
let source;
if (fixture) {
  manifest = JSON.parse(readFileSync(resolve(fixture), 'utf8'));
  source = 'fixture';
} else if (KEY && URL_) {
  const res = await fetch(`${URL_}/rest/v1/rpc/offers_site_manifest`, {
    method: 'POST',
    headers: { apikey: KEY, Authorization: `Bearer ${KEY}`, 'Content-Type': 'application/json' },
    body: '{}',
  });
  if (!res.ok) {
    console.error(`offers-build: offers_site_manifest HTTP ${res.status} ${(await res.text()).slice(0, 200)}`);
    process.exit(1);
  }
  manifest = await res.json();
  source = 'supabase';
} else {
  write({ source: 'none' });
  console.log('NOTE: offers from the dashboard skipped (no SUPABASE_SERVICE_ROLE_KEY) — the pages use content/offers.json');
  process.exit(0);
}
const offers = Array.isArray(manifest.offers) ? manifest.offers : [];
write({ source, at: manifest.at ?? new Date().toISOString(), today: manifest.today ?? null, offers, popup: manifest.popup ?? null });
console.log(`✓ offers (${source}): ${offers.length} live offer(s)${manifest.popup ? ' + a pop-up' : ''}`);
